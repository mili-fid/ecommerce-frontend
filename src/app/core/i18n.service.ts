import { Injectable } from '@angular/core';

export type Lang = 'en' | 'fr';

/**
 * Multilingual support (spec 5.4).
 * A lightweight runtime translation system:
 * - two dictionaries (EN / FR) keyed by short identifiers
 * - t(key) returns the string in the current language
 * - the `t` pipe (impure) re-evaluates on every change detection cycle,
 *   so toggling the language re-renders every visible string instantly
 * - the choice is persisted in localStorage
 */
@Injectable({ providedIn: 'root' })
export class I18nService {
  lang: Lang = (localStorage.getItem('lang') as Lang) || 'en';

  toggle() {
    this.set(this.lang === 'en' ? 'fr' : 'en');
  }

  set(lang: Lang) {
    this.lang = lang;
    localStorage.setItem('lang', lang);
  }

  t(key: string): string {
    return DICT[this.lang][key] ?? DICT['en'][key] ?? key;
  }
}

